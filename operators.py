#Operators in python
#Arithmetic Operators: +,-,*,/,%,**,//
num1=7
num2=2

print("num1 + num2=", num1+num2)
print("num1 - num2=", num1-num2)
print("num1 * num2=", num1*num2)
print("num1 / num2=", num1/num2)
print("num1 % num2=", num1%num2) #Modulus-Remainder
print("num1 // num2=", num1//num2) #Floor division-Quotient
print("num1 ** num2=", num1**num2) #Exponent-Power

#Assignment Operators: =, +=, -=, *=, /=, %=, **=, //=
